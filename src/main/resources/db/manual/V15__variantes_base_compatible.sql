
-- SEBAS COLLECTION SAAS
-- FASE 1: BASE PARA VARIANTES OPCIONALES
-- No elimina ni actualiza registros existentes.
-- PostgreSQL / Supabase

BEGIN;

-- 1. Catalogo de colores por tienda.
CREATE TABLE IF NOT EXISTS public.saas_colores_tienda (
    id_color BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tienda_id BIGINT NOT NULL
        REFERENCES public.tiendas(id) ON DELETE CASCADE,
    nombre VARCHAR(60) NOT NULL,
    codigo_hex VARCHAR(7),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT ck_saas_color_nombre
        CHECK (length(btrim(nombre)) > 0),

    CONSTRAINT ck_saas_color_hex
        CHECK (
            codigo_hex IS NULL OR
            codigo_hex ~ '^#[0-9A-Fa-f]{6}$'
        )
);

-- Evitar colores duplicados dentro de una tienda.
CREATE UNIQUE INDEX IF NOT EXISTS
    uq_saas_colores_tienda_nombre
ON public.saas_colores_tienda (
    tienda_id,
    lower(btrim(nombre))
);

-- 2. Tipo de variantes del producto.
-- NULL significa que todavia usa el modelo anterior.
ALTER TABLE public.productos
    ADD COLUMN IF NOT EXISTS tipo_variantes VARCHAR(20);

ALTER TABLE public.productos
    ADD COLUMN IF NOT EXISTS sistema_tallas VARCHAR(30);

-- 3. Color opcional para los registros de stock.
-- No se modifica id_producto_talla.
ALTER TABLE public.producto_tallas
    ADD COLUMN IF NOT EXISTS id_color BIGINT;

-- 4. Color opcional para fotografias.
ALTER TABLE public.producto_imagenes
    ADD COLUMN IF NOT EXISTS id_color BIGINT;

-- 5. Relaciones con el catalogo de colores.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.producto_tallas'::regclass
          AND conname = 'fk_producto_tallas_saas_color'
    ) THEN
        ALTER TABLE public.producto_tallas
        ADD CONSTRAINT fk_producto_tallas_saas_color
        FOREIGN KEY (id_color)
        REFERENCES public.saas_colores_tienda(id_color);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.producto_imagenes'::regclass
          AND conname = 'fk_producto_imagenes_saas_color'
    ) THEN
        ALTER TABLE public.producto_imagenes
        ADD CONSTRAINT fk_producto_imagenes_saas_color
        FOREIGN KEY (id_color)
        REFERENCES public.saas_colores_tienda(id_color);
    END IF;
END $$;

-- 6. Indices para futuras consultas.
CREATE INDEX IF NOT EXISTS
    idx_producto_tallas_id_color
ON public.producto_tallas(id_color);

CREATE INDEX IF NOT EXISTS
    idx_producto_imagenes_id_color
ON public.producto_imagenes(id_color);

COMMIT;
