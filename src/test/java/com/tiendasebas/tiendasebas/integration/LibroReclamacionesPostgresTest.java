package com.tiendasebas.tiendasebas.integration;

import com.tiendasebas.tiendasebas.config.TenantContext;
import com.tiendasebas.tiendasebas.service.LibroReclamacionesService;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.jdbc.support.JdbcTransactionManager;
import org.springframework.transaction.support.TransactionTemplate;

import javax.sql.DataSource;
import java.math.BigDecimal;
import java.sql.Connection;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.UUID;
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.TimeUnit;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Prueba REAL de PostgreSQL 17 aislado. Nunca usa Supabase, Azure ni una DB existente.
 * Ejecuta V20 solo dentro del cluster temporal creado por ComercialPostgresFixture.
 * El servicio trabaja como rol no propietario, sin BYPASSRLS ni privilegios globales.
 */
class LibroReclamacionesPostgresTest {
    private static final ComercialPostgresFixture pg = new ComercialPostgresFixture();
    private static JdbcTemplate root;
    private static JdbcTemplate app;
    private static LibroReclamacionesService service;
    private static TransactionTemplate transactions;
    private static long tiendaA;
    private static long tiendaB;

    @BeforeAll
    static void preparar() throws Exception {
        // Esta rutina rechaza configuraciones externas de BD antes de crear el cluster.
        pg.start();
        try {
            final String url = pg.verifiedUrl();
            root = new JdbcTemplate(ds(url, pg.getUsername(), pg.getPassword()));
            root.execute("CREATE TABLE public.tiendas (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre text NOT NULL)");
            tiendaA = root.queryForObject("INSERT INTO public.tiendas(nombre) VALUES ('Ficticia A') RETURNING id", Long.class);
            tiendaB = root.queryForObject("INSERT INTO public.tiendas(nombre) VALUES ('Ficticia B') RETURNING id", Long.class);

            // El SQL de la aplicacion se ejecuta UNICAMENTE en la fixture verificada.
            try (Connection c = root.getDataSource().getConnection()) {
                try (var stream = new ClassPathResource("db/manual/V20__libro_reclamaciones_multitienda.sql").getInputStream();
                     var statement = c.createStatement()) {
                    statement.execute(new String(stream.readAllBytes(), java.nio.charset.StandardCharsets.UTF_8));
                }
            }

            final String role = "reclamaciones_fixture_app";
            final String password = UUID.randomUUID().toString();
            root.execute("CREATE ROLE " + role + " LOGIN PASSWORD '" + password + "' NOSUPERUSER NOBYPASSRLS");
            root.execute("GRANT CONNECT ON DATABASE comercial_aislado TO " + role);
            root.execute("GRANT USAGE ON SCHEMA public TO " + role);
            root.execute("GRANT SELECT, INSERT, UPDATE ON public.saas_reclamaciones_numeracion TO " + role);
            root.execute("GRANT SELECT, INSERT, UPDATE, DELETE ON public.saas_reclamaciones TO " + role);
            root.execute("GRANT SELECT, INSERT, UPDATE, DELETE ON public.saas_reclamaciones_eventos TO " + role);
            root.execute("GRANT USAGE ON SEQUENCE public.saas_reclamaciones_id_seq, public.saas_reclamaciones_eventos_id_seq TO " + role);

            DataSource appDataSource = ds(url, role, password);
            app = new JdbcTemplate(appDataSource);
            var manager = new JdbcTransactionManager(appDataSource);
            transactions = new TransactionTemplate(manager);
            service = new LibroReclamacionesService(app, manager);
            assertFalse(root.queryForObject("SELECT rolbypassrls FROM pg_roles WHERE rolname = ?", Boolean.class, role));
            assertFalse(root.queryForObject("SELECT rolsuper FROM pg_roles WHERE rolname = ?", Boolean.class, role));
        } catch (Exception | Error ex) {
            pg.close();
            throw ex;
        }
    }

    @AfterAll
    static void finalizar() throws Exception { pg.close(); }

    private static DataSource ds(String url, String user, String pass) {
        var source = new DriverManagerDataSource();
        source.setDriverClassName("org.postgresql.Driver");
        source.setUrl(url);
        source.setUsername(user);
        source.setPassword(pass);
        return source;
    }

    private static LibroReclamacionesService.Solicitud solicitud(String nombre) {
        return new LibroReclamacionesService.Solicitud(
                "RECLAMO", nombre, "DNI", "00000000", "Domicilio ficticio",
                "persona@example.test", null, false, null, "PRODUCTO",
                "Producto de prueba", new BigDecimal("20.00"),
                "Detalle de prueba sin datos reales", "Solicito una respuesta de prueba");
    }

    private static LibroReclamacionesService.Registro registrar(long tienda, String nombre) {
        TenantContext.setCurrentTenant(tienda);
        try { return service.registrar(solicitud(nombre)); }
        finally { TenantContext.clear(); }
    }

    @Test
    void registraYNumeraPorTienda() {
        long anteriorA = root.queryForObject("SELECT COALESCE(MAX(numero_hoja), 0) FROM public.saas_reclamaciones WHERE tienda_id = ?", Long.class, tiendaA);
        long anteriorB = root.queryForObject("SELECT COALESCE(MAX(numero_hoja), 0) FROM public.saas_reclamaciones WHERE tienda_id = ?", Long.class, tiendaB);
        var a1 = registrar(tiendaA, "Registro A1");
        var b1 = registrar(tiendaB, "Registro B1");
        assertEquals(anteriorA + 1, a1.numeroHoja());
        assertEquals(anteriorB + 1, b1.numeroHoja());
        assertEquals(anteriorA + 2, registrar(tiendaA, "Registro A2").numeroHoja());
        assertEquals(1, root.queryForObject(
                "SELECT count(*) FROM public.saas_reclamaciones_eventos WHERE tienda_id = ? AND reclamacion_id = ?",
                Integer.class, tiendaA, a1.id()));
    }

    @Test
    void rlsImpideLeerYModificarOtraTienda() {
        var registroB = registrar(tiendaB, "Solo tienda B");
        var visiblesA = transactions.execute(s -> {
            app.queryForObject("SELECT set_config('app.tenant_id', ?, true)", String.class, Long.toString(tiendaA));
            Integer visibles = app.queryForObject(
                    "SELECT count(*) FROM public.saas_reclamaciones WHERE id = ?", Integer.class, registroB.id());
            Integer modificadas = app.update(
                    "UPDATE public.saas_reclamaciones_numeracion SET ultimo_numero = 999 WHERE tienda_id = ?", tiendaB);
            assertEquals(0, modificadas);
            return visibles;
        });
        assertEquals(0, visiblesA);
        assertEquals(0, root.queryForObject(
                "SELECT count(*) FROM public.saas_reclamaciones WHERE tienda_id = ? AND consumidor_nombre = 'Solo tienda B'",
                Integer.class, tiendaA));
    }

    @Test
    void sinContextoRlsNoPermiteInsertarNiVerRegistros() {
        assertThrows(Exception.class, () -> transactions.executeWithoutResult(s ->
                app.update("INSERT INTO public.saas_reclamaciones_numeracion(tienda_id, ultimo_numero) VALUES (?,1)",
                        tiendaA)));
        Integer count = transactions.execute(s -> app.queryForObject(
                "SELECT count(*) FROM public.saas_reclamaciones", Integer.class));
        assertEquals(0, count);
    }

    @Test
    void losRegistrosYEventosSonInmutables() {
        var r = registrar(tiendaA, "Inmutable");
        assertThrows(Exception.class, () -> transactions.executeWithoutResult(s -> {
            app.queryForObject("SELECT set_config('app.tenant_id', ?, true)", String.class, Long.toString(tiendaA));
            app.update("UPDATE public.saas_reclamaciones SET consumidor_nombre = 'Alterado' WHERE id = ?", r.id());
        }));
        assertThrows(Exception.class, () -> transactions.executeWithoutResult(s -> {
            app.queryForObject("SELECT set_config('app.tenant_id', ?, true)", String.class, Long.toString(tiendaA));
            app.update("DELETE FROM public.saas_reclamaciones_eventos WHERE reclamacion_id = ?", r.id());
        }));
        assertEquals("Inmutable", root.queryForObject(
                "SELECT consumidor_nombre FROM public.saas_reclamaciones WHERE id = ?", String.class, r.id()));
    }

    @Test
    void solicitudesConcurrentesNoDuplicanNumeros() {
        final int cantidad = 8;
        List<CompletableFuture<Long>> tasks = new ArrayList<>();
        for (int i = 0; i < cantidad; i++) {
            final int indice = i;
            tasks.add(CompletableFuture.supplyAsync(() -> registrar(tiendaA, "Concurrente " + indice).numeroHoja()));
        }
        List<Long> numeros = new ArrayList<>();
        for (var task : tasks) numeros.add(task.orTimeout(30, TimeUnit.SECONDS).join());
        assertEquals(cantidad, new HashSet<>(numeros).size());
        assertEquals(cantidad, root.queryForObject(
                "SELECT count(*) FROM public.saas_reclamaciones WHERE tienda_id = ? AND consumidor_nombre LIKE 'Concurrente %'",
                Integer.class, tiendaA));
    }
}
