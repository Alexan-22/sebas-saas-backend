package com.tiendasebas.tiendasebas.integration;

import com.tiendasebas.tiendasebas.config.TenantContext;
import com.tiendasebas.tiendasebas.service.ConstanciaReclamacionesService;
import com.tiendasebas.tiendasebas.service.LibroReclamacionesService;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.jdbc.support.JdbcTransactionManager;
import org.springframework.web.server.ResponseStatusException;

import javax.sql.DataSource;
import java.math.BigDecimal;
import java.sql.Connection;
import java.nio.charset.StandardCharsets;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Ejecuta SQL V20 UNICAMENTE en el PostgreSQL 17 temporal y verificado.
 * Las consultas RLS se hacen mediante un rol de aplicación no privilegiado.
 * No prueba autorización HTTP ni producción: solo el contrato interno de lectura.
 */
class ConstanciaReclamacionesPostgresTest {
    private static final ComercialPostgresFixture pg = new ComercialPostgresFixture();
    private static JdbcTemplate root;
    private static JdbcTemplate app;
    private static LibroReclamacionesService registro;
    private static ConstanciaReclamacionesService constancias;
    private static long tiendaA;
    private static long tiendaB;

    @BeforeAll
    static void preparar() throws Exception {
        pg.start(); // rechaza configuraciones externas antes de iniciar cualquier base
        try {
            String url = pg.verifiedUrl();
            root = new JdbcTemplate(ds(url, pg.getUsername(), pg.getPassword()));
            root.execute("CREATE TABLE public.tiendas (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre text NOT NULL)");
            tiendaA = root.queryForObject("INSERT INTO public.tiendas(nombre) VALUES ('Ficticia A') RETURNING id", Long.class);
            tiendaB = root.queryForObject("INSERT INTO public.tiendas(nombre) VALUES ('Ficticia B') RETURNING id", Long.class);

            try (Connection c = root.getDataSource().getConnection();
                 var sql = new ClassPathResource("db/manual/V20__libro_reclamaciones_multitienda.sql").getInputStream();
                 var stmt = c.createStatement()) {
                stmt.execute(new String(sql.readAllBytes(), StandardCharsets.UTF_8));
            }

            String role = "constancias_fixture_app";
            String password = UUID.randomUUID().toString().replace("'", "");
            root.execute("CREATE ROLE " + role + " LOGIN PASSWORD '" + password + "' NOSUPERUSER NOBYPASSRLS");
            root.execute("GRANT CONNECT ON DATABASE comercial_aislado TO " + role);
            root.execute("GRANT USAGE ON SCHEMA public TO " + role);
            root.execute("GRANT SELECT, INSERT, UPDATE ON public.saas_reclamaciones_numeracion TO " + role);
            root.execute("GRANT SELECT, INSERT ON public.saas_reclamaciones TO " + role);
            root.execute("GRANT SELECT, INSERT ON public.saas_reclamaciones_eventos TO " + role);
            root.execute("GRANT USAGE ON SEQUENCE public.saas_reclamaciones_id_seq, public.saas_reclamaciones_eventos_id_seq TO " + role);
            assertFalse(root.queryForObject("SELECT rolsuper OR rolbypassrls FROM pg_roles WHERE rolname=?", Boolean.class, role));

            DataSource data = ds(url, role, password);
            app = new JdbcTemplate(data);
            JdbcTransactionManager manager = new JdbcTransactionManager(data);
            registro = new LibroReclamacionesService(app, manager);
            constancias = new ConstanciaReclamacionesService(app, manager);
        } catch (Exception | Error ex) {
            pg.close();
            throw ex;
        }
    }

    @AfterAll
    static void finalizar() throws Exception { pg.close(); }

    private static DataSource ds(String url, String usuario, String password) {
        var ds = new DriverManagerDataSource();
        ds.setDriverClassName("org.postgresql.Driver");
        ds.setUrl(url);
        ds.setUsername(usuario);
        ds.setPassword(password);
        return ds;
    }

    private static LibroReclamacionesService.Solicitud solicitud(String nombre) {
        return new LibroReclamacionesService.Solicitud(
                "RECLAMO", nombre, "DNI", "00000000", "Domicilio ficticio",
                "ejemplo@example.test", null, false, null, "PRODUCTO",
                "Bien ficticio", new BigDecimal("25.50"),
                "Detalle sin datos personales reales", "Pedido de prueba");
    }

    private static LibroReclamacionesService.Registro registrar(long tenant, String nombre) {
        TenantContext.setCurrentTenant(tenant);
        try { return registro.registrar(solicitud(nombre)); }
        finally { TenantContext.clear(); }
    }

    private static ConstanciaReclamacionesService.Hoja obtener(long tenant, long numero) {
        TenantContext.setCurrentTenant(tenant);
        try { return constancias.obtener(numero); }
        finally { TenantContext.clear(); }
    }

    @Test
    void recuperaLosDatosQueFueronPersistidos() {
        var r = registrar(tiendaA, "Consumidor ficticio A");
        var hoja = obtener(tiendaA, r.numeroHoja());
        assertEquals(r.numeroHoja(), hoja.numeroHoja());
        assertNotNull(hoja.recibidoEn());
        assertEquals("Consumidor ficticio A", hoja.consumidorNombre());
        assertEquals("00000000", hoja.documentoNumero());
        assertEquals("RECLAMO", hoja.tipo());
        assertEquals("Bien ficticio", hoja.bienDescripcion());
        assertEquals(0, new BigDecimal("25.50").compareTo(hoja.montoReclamado()));
        assertEquals("Pedido de prueba", hoja.pedido());
    }

    @Test
    void noEntregaDatosDeOtraTiendaAunqueCoincidaElNumero() {
        var ra = registrar(tiendaA, "Solo A");
        var rb = registrar(tiendaB, "Solo B");
        // Los correlativos se repiten legítimamente entre tiendas.
        // Cada tenant debe recibir exclusivamente su propio registro.
        var lecturaA = obtener(tiendaA, ra.numeroHoja());
        var lecturaB = obtener(tiendaB, rb.numeroHoja());
        assertEquals("Solo A", lecturaA.consumidorNombre());
        assertEquals("Solo B", lecturaB.consumidorNombre());
        assertNotEquals(lecturaA.consumidorNombre(), lecturaB.consumidorNombre());

        // Con el tenant A no puede recuperar una hoja que solo existe en B.
        long maxA = root.queryForObject(
                "SELECT coalesce(max(numero_hoja),0) FROM public.saas_reclamaciones WHERE tienda_id=?",
                Long.class, tiendaA);
        var soloB = registrar(tiendaB, "Exclusivo B");
        while (soloB.numeroHoja() <= maxA) {
            soloB = registrar(tiendaB, "Exclusivo B");
        }
        long numeroExclusivoB = soloB.numeroHoja();
        assertThrows(ResponseStatusException.class, () -> obtener(tiendaA, numeroExclusivoB));
    }

    @Test
    void exigeTenantYNumeroValidos() {
        TenantContext.clear();
        assertThrows(ResponseStatusException.class, () -> constancias.obtener(1));
        TenantContext.setCurrentTenant(tiendaA);
        try { assertThrows(ResponseStatusException.class, () -> constancias.obtener(0)); }
        finally { TenantContext.clear(); }
    }
}
