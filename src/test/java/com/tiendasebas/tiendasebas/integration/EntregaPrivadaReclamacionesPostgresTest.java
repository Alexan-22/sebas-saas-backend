package com.tiendasebas.tiendasebas.integration;

import com.tiendasebas.tiendasebas.config.TenantContext;
import com.tiendasebas.tiendasebas.service.*;
import org.junit.jupiter.api.*;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.jdbc.support.JdbcTransactionManager;
import org.springframework.web.server.ResponseStatusException;

import javax.sql.DataSource;
import java.math.BigDecimal;
import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.util.UUID;
import static org.junit.jupiter.api.Assertions.*;

/** Fixture PostgreSQL local efimera; NUNCA conecta a Azure. */
class EntregaPrivadaReclamacionesPostgresTest {
    private static final ComercialPostgresFixture pg = new ComercialPostgresFixture();
    private static JdbcTemplate root, app;
    private static EntregaPrivadaReclamacionesService servicio;
    private static long a, b;

    @BeforeAll static void preparar() throws Exception {
        pg.start();
        try {
            String url = pg.verifiedUrl();
            root = new JdbcTemplate(ds(url, pg.getUsername(), pg.getPassword()));
            root.execute("CREATE TABLE public.tiendas (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre text NOT NULL)");
            a = root.queryForObject("INSERT INTO public.tiendas(nombre) VALUES ('Tienda ficticia A') RETURNING id", Long.class);
            b = root.queryForObject("INSERT INTO public.tiendas(nombre) VALUES ('Tienda ficticia B') RETURNING id", Long.class);
            aplicar("db/manual/V23__libro_reclamaciones_multitienda.sql");
            aplicar("db/manual/V24__reclamaciones_accesos_y_proveedor.sql");
            String role = "entrega_fixture_app";
            String pass = UUID.randomUUID().toString().replace("'", "");
            root.execute("CREATE ROLE " + role + " LOGIN PASSWORD '" + pass + "' NOSUPERUSER NOBYPASSRLS");
            root.execute("GRANT CONNECT ON DATABASE comercial_aislado TO " + role);
            root.execute("GRANT USAGE ON SCHEMA public TO " + role);
            root.execute("GRANT SELECT, INSERT, UPDATE ON public.saas_reclamaciones_numeracion TO " + role);
            root.execute("GRANT SELECT, INSERT ON public.saas_reclamaciones TO " + role);
            root.execute("GRANT SELECT, INSERT ON public.saas_reclamaciones_eventos TO " + role);
            root.execute("GRANT SELECT, INSERT ON public.saas_reclamaciones_accesos TO " + role);
            root.execute("GRANT SELECT ON public.saas_reclamaciones_proveedores TO " + role);
            root.execute("GRANT USAGE ON SEQUENCE public.saas_reclamaciones_id_seq, public.saas_reclamaciones_eventos_id_seq TO " + role);
            assertFalse(root.queryForObject("SELECT rolsuper OR rolbypassrls FROM pg_roles WHERE rolname=?", Boolean.class, role));
            DataSource data = ds(url, role, pass);
            app = new JdbcTemplate(data);
            var tm = new JdbcTransactionManager(data);
            servicio = new EntregaPrivadaReclamacionesService(app, tm,
                    new LibroReclamacionesService(app, tm), new ConstanciaReclamacionesService(app, tm),
                    new ConstanciaReclamacionesDocumentoService());
            // Solo fixture: identidad legal ficticia, nunca datos de produccion.
            root.update("INSERT INTO public.saas_reclamaciones_proveedores(tienda_id,razon_social,ruc,domicilio_legal,verificado) VALUES (?, 'Proveedor de prueba', '00000000000', 'Domicilio de prueba',true)", a);
            root.update("INSERT INTO public.saas_reclamaciones_proveedores(tienda_id,razon_social,ruc,domicilio_legal,verificado) VALUES (?, 'Proveedor B', '11111111111', 'Otro domicilio de prueba',true)", b);
        } catch (Exception | Error ex) { pg.close(); throw ex; }
    }

    private static void aplicar(String resource) throws Exception {
        try (Connection c = root.getDataSource().getConnection();
             var sql = new ClassPathResource(resource).getInputStream();
             var stmt = c.createStatement()) {
            stmt.execute(new String(sql.readAllBytes(), StandardCharsets.UTF_8));
        }
    }

    @AfterAll static void finalizar() throws Exception { TenantContext.clear(); pg.close(); }

    private static DataSource ds(String url, String user, String password) {
        var ds = new DriverManagerDataSource();
        ds.setDriverClassName("org.postgresql.Driver"); ds.setUrl(url);
        ds.setUsername(user); ds.setPassword(password); return ds;
    }
    private static LibroReclamacionesService.Solicitud solicitud(String consumidor) {
        return new LibroReclamacionesService.Solicitud("RECLAMO", consumidor, "DNI", "00000000",
                "Calle ficticia", "persona@example.test", null, false, null, "PRODUCTO",
                "Producto de prueba", new BigDecimal("12.00"), "Descripcion de prueba", "Solicitud de prueba");
    }
    private static EntregaPrivadaReclamacionesService.Confirmacion registrar(long tenant, String nombre) {
        TenantContext.setCurrentTenant(tenant);
        try { return servicio.registrar(solicitud(nombre)); }
        finally { TenantContext.clear(); }
    }
    private static String obtener(long tenant, String token) {
        TenantContext.setCurrentTenant(tenant);
        try { return servicio.html(token); }
        finally { TenantContext.clear(); }
    }

    @Test void tokenHashYConstanciaSePersistenSinGuardarSecreto() {
        var r = registrar(a, "Comprador ficticio");
        assertEquals(43, r.tokenConstancia().length());
        assertEquals(1, root.queryForObject("SELECT count(*) FROM public.saas_reclamaciones_accesos WHERE tienda_id=? AND token_sha256 <> ?", Integer.class, a, r.tokenConstancia()));
        String html = obtener(a, r.tokenConstancia());
        assertTrue(html.contains("Comprador ficticio"));
        assertTrue(html.contains("Proveedor de prueba"));
        assertTrue(html.contains("00000000000"));
    }

    @Test void tokenDeUnaTiendaNoFuncionaEnOtra() {
        var r = registrar(a, "Privado A");
        assertThrows(ResponseStatusException.class, () -> obtener(b, r.tokenConstancia()));
        assertTrue(obtener(a, r.tokenConstancia()).contains("Privado A"));
    }

    @Test void tokenFalsoOInvalidoNuncaDevuelveConstancia() {
        var r = registrar(b, "Privado B");
        assertThrows(ResponseStatusException.class, () -> obtener(b, "invalid"));
        String otro = "A".repeat(43);
        assertThrows(ResponseStatusException.class, () -> obtener(b, otro));
        assertTrue(obtener(b, r.tokenConstancia()).contains("Privado B"));
    }

    @Test void proveedorNoVerificadoBloqueaRegistroSinCrearHoja() {
        root.update("UPDATE public.saas_reclamaciones_proveedores SET verificado=false WHERE tienda_id=?", b);
        try {
            assertThrows(ResponseStatusException.class, () -> registrar(b, "No debe guardarse"));
            assertEquals(0, root.queryForObject("SELECT count(*) FROM public.saas_reclamaciones WHERE consumidor_nombre = 'No debe guardarse'", Integer.class));
        } finally {
            root.update("UPDATE public.saas_reclamaciones_proveedores SET verificado=true WHERE tienda_id=?", b);
        }
    }
}
